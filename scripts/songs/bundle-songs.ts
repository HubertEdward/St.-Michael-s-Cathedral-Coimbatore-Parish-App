// Packs the songbook into the parishioner app, so every song is on the phone itself: compact, gzipped, and
// written as apps/mobile/src/songbook/songbook.data.js (about 340 KB, from 1.7 MB of text).
//
//   npm run songs:bundle      after npm run songs:fetch; run it before building the app
//
// The file is gitignored: the repo is public, and the lyrics belong to their composers.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

import { songOccasions } from '../../packages/core/src/types';
import { occasions, type SongFile } from './occasions';

const source = join(__dirname, '..', '..', '..', '..', 'Songs', 'iraialaihal.json');
const target = join(__dirname, '..', '..', 'apps', 'mobile', 'src', 'songbook', 'songbook.data.js');

const book = JSON.parse(readFileSync(source, 'utf8')) as SongFile;
// Each song as [number, title, occasions (by position in songOccasions), stanzas]: shorter than named fields.
const packed = book.songs.map((s) => [s.number, s.title, s.occasions.map((o) => songOccasions.indexOf(occasions[o].key)), s.stanzas]);
const json = JSON.stringify(packed);
const gz = gzipSync(json, { level: 9 });

writeFileSync(
  target,
  `// Generated by npm run songs:bundle from ${book.source}, fetched ${book.fetchedOn}.\n` +
    '// Not committed: the repo is public, and the lyrics belong to their composers.\n' +
    `export default { fetchedOn: '${book.fetchedOn}', count: ${packed.length}, gzip: '${gz.toString('base64')}' };\n`,
);
console.log(`Packed ${packed.length} songs: ${Math.round(Buffer.byteLength(json) / 1024)} KB of text → ${Math.round(gz.length / 1024)} KB gzipped, into ${target}.`);
