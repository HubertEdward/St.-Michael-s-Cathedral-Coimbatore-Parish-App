// Packs both songbooks into the parishioner app, so every song is on the phone itself: merged, compact,
// gzipped, and written as apps/mobile/src/songbook/songbook.data.js.
//
//   npm run songs:bundle      after npm run songs:fetch; run it before building the app
//
// A song in both books is kept once, as its இறை அலைகள் entry (whose numbers match the printed book), with the
// occasions from both. The file is gitignored: the repo is public, and the lyrics belong to their composers.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { gzipSync } from 'node:zlib';

import { songBooks, songOccasions } from '../../packages/core/src/types';
import { mergeBooks } from './merge';
import type { SongFile } from './occasions';

const songsFolder = join(__dirname, '..', '..', '..', '..', 'Songs');
const target = join(__dirname, '..', '..', 'apps', 'mobile', 'src', 'songbook', 'songbook.data.js');

function main() {
  const files = songBooks.map((book) => JSON.parse(readFileSync(join(songsFolder, `${book}.json`), 'utf8')) as SongFile);
  const { kept, duplicates } = mergeBooks(files);
  // Each song as [book, number, title, occasions, stanzas], books and occasions by position: shorter than names.
  const packed = kept.map(({ book, song }) => [
    songBooks.indexOf(book),
    song.number,
    song.title,
    song.occasions.map((o) => songOccasions.indexOf(o)),
    song.stanzas,
  ]);
  const json = JSON.stringify(packed);
  const gz = gzipSync(json, { level: 9 });
  const sources = files.map((f) => `${f.source}, fetched ${f.fetchedOn}`).join('; ');
  writeFileSync(
    target,
    `// Generated by npm run songs:bundle from ${sources}.\n` +
      '// Not committed: the repo is public, and the lyrics belong to their composers.\n' +
      `export default { count: ${packed.length}, gzip: '${gz.toString('base64')}' };\n`,
  );
  const perBook = songBooks.map((book) => `${kept.filter((k) => k.book === book).length} ${book}`).join(', ');
  console.log(
    `Packed ${packed.length} songs (${perBook}; ${duplicates} in both books kept once): ${Math.round(Buffer.byteLength(json) / 1024)} KB of text → ${Math.round(gz.length / 1024)} KB gzipped.`,
  );
}

main();
